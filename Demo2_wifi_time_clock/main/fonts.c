static const uint8_t g_minus[5] = {0x08, 0x08, 0x08, 0x08, 0x08};
static const uint8_t g_colon[5] = {0x00, 0x36, 0x36, 0x00, 0x00};
static const uint8_t g_dot[5] = {0x00, 0x60, 0x60, 0x00, 0x00};
static const uint8_t g_slash[5] = {0x20, 0x10, 0x08, 0x04, 0x02};
static const uint8_t g_space[5] = {0x00, 0x00, 0x00, 0x00, 0x00};

const uint8_t *font5x7_lookup(char ch)
{
    if (ch >= '0' && ch <= '9') {
        return g_digit[ch - '0'];
    }
    if (ch >= 'a' && ch <= 'z') {
        ch = (char)(ch - 'a' + 'A');
    }
    if (ch >= 'A' && ch <= 'Z') {
        return g_alpha[ch - 'A'];
    }
    switch (ch) {
    case '-':
        return g_minus;
    case ':':
        return g_colon;
    case '.':
        return g_dot;
    case '/':
        return g_slash;
    case ' ':
        return g_space;
    default:
        return NULL;
    }
}

